CREATE SEQUENCE short_url_seq START WITH 916132832 INCREMENT BY 1;

CREATE TABLE short_urls (
    id            BIGINT        PRIMARY KEY,
    code          VARCHAR(32)   NOT NULL,
    original_url  VARCHAR(2048) NOT NULL,
    custom_alias  BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP     NOT NULL,
    expires_at    TIMESTAMP,
    click_count   BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_short_urls_code UNIQUE (code)
);

CREATE TABLE click_events (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url_id BIGINT      NOT NULL,
    clicked_at  TIMESTAMP    NOT NULL,
    referrer    VARCHAR(512),
    user_agent  VARCHAR(512),
    CONSTRAINT fk_click_events_url FOREIGN KEY (short_url_id) REFERENCES short_urls (id) ON DELETE CASCADE
);

CREATE INDEX idx_click_events_url_time ON click_events (short_url_id, clicked_at);
